-- 枫叶节 / 维萨尔节 礼物盒掉落配置（NPC 9201030 梅普克劳斯、9201091 奥蓬戈）
-- ============================================================
-- 对应脚本：
--   scripts-zh-CN/npc/9201030.js  梅普克劳斯（Maple Claws）—— 枫叶节兑换
--   scripts-zh-CN/npc/9201091.js  奥蓬戈（O-Pongo）      —— 维萨尔节兑换
--
-- ★ 掉落开关：questid = 8209
--   本迁移所有掉落行都带 questid = 8209，由上面两个 NPC 脚本维护：
--     玩家是活动参与者(任务 4997 或 4998 已完成) -> 8209 置为 STARTED("ing") -> 掉落
--     玩家没参加                                  -> 8209 保持 NOT_STARTED(0)  -> 不掉
--     8209 置为 COMPLETED("end")                  -> 立即停掉（"关"的状态）
--
--   原理（org.gms.client.Character#needQuestItem）：
--     questid <= 0            -> 恒掉
--     未接(0)   -> 查 Quest.wz 的"接取所需道具"，8209 无此数据 -> 返回 MIN_VALUE -> 不掉
--     进行中(1) -> 查 Quest.wz 的"完成所需道具"，8209 无此数据 -> 返回 MAX_VALUE -> 掉
--     已完成(2) -> 直接返回 false -> 不掉
--   且 MapleMap#spawnDrop / MapItem#sendSpawnData 都会用 needQuestItem 过滤发包，
--   所以未参加的玩家连"地上有这个道具"都看不到，不是"看得到但捡不起来"。
--
--   注意：必须用 cm.updateQuestCustomData(8209,"ing"/"end")（会同时改 status），
--   只用 setCustomData 不改 status 是拦不住掉落的。
--
-- 等级分段 -> 礼物盒道具（与脚本 getPresentItemByLevel() 完全一致）：
--   Lv 10 - 20  -> 4031443 (红/绿 礼物盒)
--   Lv 21 - 30  -> 4031440 (红/白 礼物盒)
--   Lv 31 - 40  -> 4031441 (红/蓝 礼物盒)
--   Lv 41 - 60  -> 4031439 (蓝/白 礼物盒)
--   Lv 61 +     -> 4031442 (白/绿 礼物盒)
--
-- 其它说明：
-- 1. 只给 10 级及以上的怪物配置掉落；10 级以下的怪物不掉（活动面向 10 级以上玩家）。
-- 2. chance 分母是 1000000，200000 = 20% 基础概率；实际概率 = chance/1000000
--    × 频道掉率 × 怪物卡片加成。要整体调整掉率，只改下面的 @present_chance 即可。
--    要临时彻底关掉活动：SET @present_chance = 0; 或在跑完后
--      UPDATE `drop_data` SET `chance` = 0 WHERE `questid` = 8209;
-- 3. 本迁移不写 quest / queststatus 表：8200 8201 8202 8203 8209 都用
--    cm.getQuestRecord()/updateQuestCustomData() 的 customData 存储，
--    QuestRepository.getInstance() 会自动补齐缺失的任务定义，不需要任务表数据。
-- 4. 怪物清单直接从 gms-handler/wz/Mob.wz/*.img.xml 的 info/level 生成，
--    含少量脚本召唤怪 / 活动怪；如需剔除，按 dropperid 手动删掉对应行即可。
-- ============================================================

